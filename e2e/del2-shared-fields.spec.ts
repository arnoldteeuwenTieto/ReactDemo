import { schoolOpeningAction } from './helpers/schoolActions'
import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('Del 2 shared fields drive grades, badges and field states without changing permissions', async ({ page }) => {
  await page.goto('./')
  await schoolOpeningAction(page, 'Fjordgløtt barneskole', '2026').click()
  await page.getByRole('button', { name: 'Gå til rapporteringen', exact: true }).click()
  const nav = page.getByRole('navigation', { name: 'Grunnskoleseksjoner', exact: true })
  const del2 = nav.getByRole('button', { name: 'Om skolen', exact: true })
  const lower = page.getByRole('combobox', { name: 'B. Hva er normalt laveste trinn ved skolen?', exact: true })
  const upper = page.getByRole('combobox', { name: 'C. Hva er normalt høyeste trinn ved skolen?', exact: true })
  await del2.click()
  await expect(del2.locator('.section-issue-badge')).toHaveText('4')
  await expect(lower).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await lower.focus()
  await expect(page.getByRole('tooltip')).toContainText('GG_228_Laveste_Trinn_Paa_Skolen')
  await lower.selectOption('2'); await upper.selectOption('1')
  await expect(upper).toHaveAttribute('aria-invalid', 'true')
  await expect(upper).toHaveAccessibleDescription(/Verdien i 2C/)
  await expect(upper).toHaveCSS('border-top-color', await page.locator(':root').evaluate(el => getComputedStyle(el).getPropertyValue('--field-error-border').trim()).then(async color => {
    return page.evaluate(color => { const el = document.createElement('span'); el.style.color = color; document.body.append(el); const result = getComputedStyle(el).color; el.remove(); return result }, color)
  }))
  await upper.selectOption('6')
  const language = page.getByRole('group', { name: 'A. Skolens målform', exact: true }).getByRole('radio', { name: 'Bokmål', exact: true })
  await language.check(); await language.focus()
  await expect(page.getByRole('tooltip')).toContainText('GG_227_Skolens_Maalform')
  await expect(language).toHaveCSS('background-color', 'rgb(241, 243, 245)')
  const noSfo = page.getByRole('radio', { name: 'Nei', exact: true })
  await noSfo.check() // false is a populated answer, not empty.
  await expect(noSfo).toHaveCSS('background-color', 'rgb(241, 243, 245)')
  await expect(del2.locator('.section-issue-badge')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'C. Hva er normalt høyeste trinn ved skolen?', exact: true }).getByRole('status')).toHaveText('Lagret')
  await page.keyboard.press('Escape')
  expect((await new AxeBuilder({ page }).include('main').withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()).violations).toEqual([])
  await nav.getByRole('button', { name: 'Elever og timer', exact: true }).click()
  const grade1 = page.locator('input[data-field="GG_1_Antall_Elever_Trinn1_Gutter"]')
  const grade6 = page.locator('input[data-field="GG_16_Antall_Elever_Trinn6_Gutter"]')
  await expect(grade1).toBeDisabled(); await expect(grade1).toHaveCSS('background-color', 'rgb(234, 240, 247)')
  await expect(grade1).toHaveCSS('border-top-color', 'rgb(187, 203, 221)')
  const lock = page.locator('.field-control').filter({ has: grade1 }).getByRole('button')
  await expect(lock).toHaveCSS('color', 'rgb(98, 120, 148)'); await lock.focus()
  await expect(lock).toHaveAccessibleDescription(/Del 2|del 2/)
  await expect(grade6).toBeEnabled(); await grade6.fill('0')
  await expect(grade6).toHaveCSS('background-color', 'rgb(241, 243, 245)')
  await expect(page.locator('input[data-field="GG_18_Antall_Elever_Trinn6_Sum"]')).toHaveCSS('background-color', 'rgb(217, 221, 227)')
  await page.getByRole('combobox', { name: 'Demonstrasjonsbruker DEMO', exact: true }).selectOption('demo-udir-support')
  await expect(grade6).toBeDisabled(); await expect(grade6).toHaveCSS('background-color', 'rgb(241, 243, 245)')
  await del2.click(); await expect(language).toBeDisabled(); await expect(language).toBeChecked()
  await expect(lower).toHaveCSS('background-color', 'rgb(241, 243, 245)')
  await expect(del2.locator('.section-issue-badge')).toHaveCount(0)
})
